"""Inventory of the extracted log files per testbed (plan 4.4, M1)."""

from collections import Counter
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path

from logtriage.config import LogSources, Settings, load_sources
from logtriage.data.labels import (
    Phase,
    cross_check_phases,
    read_attack_steps,
    read_exfil_interval,
    read_phase_intervals,
    render_phase_section,
    summarize_label_file,
    write_phases_csv,
)

CHUNK_BYTES = 8 * 1024 * 1024


@dataclass
class FileRecord:
    """One extracted file under `gather/`."""

    path: str
    host: str
    size: int
    lines: int
    log_type: str | None
    labeled_lines: int = 0
    label_counts: Counter[str] = field(default_factory=Counter)
    has_labels: bool = False


def count_lines(path: Path, chunk_bytes: int = CHUNK_BYTES) -> int:
    """Count lines by streaming binary chunks; a final line without newline counts."""
    count = 0
    last = b"\n"
    with path.open("rb") as handle:
        while chunk := handle.read(chunk_bytes):
            count += chunk.count(b"\n")
            last = chunk[-1:]
    return count if last == b"\n" else count + 1


def build_inventory(testbed_dir: Path, sources: LogSources) -> list[FileRecord]:
    """Scan `gather/` and `labels/` of an extracted testbed.

    Args:
        testbed_dir: `data/raw/<testbed>`.
        sources: Log source patterns.

    Returns:
        One record per file under `gather/`, sorted by path.

    Raises:
        FileNotFoundError: If a label file has no matching log file.
    """
    records: dict[str, FileRecord] = {}
    for path in sorted((testbed_dir / "gather").rglob("*")):
        if path.is_file():
            relative = path.relative_to(testbed_dir).as_posix()
            records[relative] = FileRecord(
                path=relative,
                host=relative.split("/")[1],
                size=path.stat().st_size,
                lines=count_lines(path),
                log_type=sources.log_type(relative),
            )
    labels_dir = testbed_dir / "labels"
    for path in sorted(labels_dir.rglob("*")):
        if path.is_file():
            relative = "gather/" + path.relative_to(labels_dir).as_posix()
            if relative not in records:
                raise FileNotFoundError(f"{path}: no matching log file {relative}")
            summary = summarize_label_file(path)
            record = records[relative]
            record.has_labels = True
            record.labeled_lines = summary.labeled_lines
            record.label_counts = summary.label_counts
    return list(records.values())


def unmapped_labeled_files(records: Iterable[FileRecord], sources: LogSources) -> list[str]:
    """Return labeled files that are neither in a log family nor known as other labeled."""
    return [
        record.path
        for record in records
        if record.has_labels
        and record.log_type is None
        and not sources.is_other_labeled(record.path)
    ]


def _table(header: list[str], rows: Iterable[list[object]]) -> list[str]:
    """Render a Markdown table."""
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return lines


def _mb(size: int) -> str:
    """Format a byte count in MB."""
    return f"{size / 1e6:.2f}"


def render_report(
    testbed: str, records: list[FileRecord], sources: LogSources, extra_sections: list[str]
) -> str:
    """Render `reports/inventory_<testbed>.md`.

    Args:
        testbed: Testbed name.
        records: Output of `build_inventory`.
        sources: Log source patterns.
        extra_sections: Markdown appended after the inventory sections.

    Returns:
        The report text.
    """
    labeled = [record for record in records if record.has_labels]
    label_totals: Counter[str] = Counter()
    for record in labeled:
        label_totals.update(record.label_counts)

    by_type: dict[str, list[FileRecord]] = {}
    by_host: dict[str, list[FileRecord]] = {}
    for record in records:
        by_type.setdefault(record.log_type or "(none)", []).append(record)
        by_host.setdefault(record.host, []).append(record)

    def totals(key: str, group: list[FileRecord]) -> list[object]:
        size = sum(record.size for record in group)
        lines = sum(record.lines for record in group)
        labeled_lines = sum(record.labeled_lines for record in group)
        return [key, len(group), _mb(size), lines, labeled_lines]

    summary_header = ["files", "size MB", "lines", "labeled lines"]
    out = [
        f"# Inventory: {testbed}",
        "",
        "Generated by `logtriage inventory`. It covers the files selected by the extraction",
        "rules in `configs/sources.yaml`, not the whole archive. Line counts count newlines,",
        "so they mean little for the binary files under `attacker_0`.",
        "",
        f"- Hosts with extracted files: {len(by_host)}",
        f"- Files: {len(records)}",
        f"- Size: {_mb(sum(record.size for record in records))} MB",
        f"- Lines: {sum(record.lines for record in records)}",
        f"- Labeled files: {len(labeled)}",
        f"- Labeled lines: {sum(record.labeled_lines for record in records)}",
        "",
        "## By log type",
        "",
        *_table(
            ["log type", *summary_header],
            [totals(key, group) for key, group in sorted(by_type.items())],
        ),
        "",
        "## By host",
        "",
        *_table(
            ["host", *summary_header],
            [totals(key, group) for key, group in sorted(by_host.items())],
        ),
        "",
        "## Labeled files",
        "",
        *_table(
            ["file", "log type", "lines", "labeled lines"],
            [
                [
                    f"`{record.path}`",
                    record.log_type
                    or ("other" if sources.is_other_labeled(record.path) else "UNMAPPED"),
                    record.lines,
                    record.labeled_lines,
                ]
                for record in labeled
            ],
        ),
        "",
        "## Label counts",
        "",
        "A line can carry several labels, so these counts add up to more than the labeled lines.",
        "",
        *_table(["raw label", "lines"], [[k, v] for k, v in sorted(label_totals.items())]),
        "",
        "## Label counts per file",
        "",
        *_table(
            ["file", "raw label", "lines"],
            [
                [f"`{record.path}`", label, count]
                for record in labeled
                for label, count in sorted(record.label_counts.items())
            ],
        ),
        "",
        "## All files",
        "",
        *_table(
            ["file", "log type", "size MB", "lines", "labels"],
            [
                [
                    f"`{record.path}`",
                    record.log_type or "-",
                    _mb(record.size),
                    record.lines,
                    "yes" if record.has_labels else "no",
                ]
                for record in records
            ],
        ),
        "",
    ]
    for section in extra_sections:
        out += [section, ""]
    return "\n".join(out)


def run_inventory(testbed: str, settings: Settings) -> Path:
    """Write `reports/inventory_<testbed>.md` and `data_meta/phases_<testbed>.csv`.

    Args:
        testbed: Testbed name.
        settings: Loaded settings.

    Returns:
        The path of the report.

    Raises:
        FileNotFoundError: If the testbed or AIT-ADS has not been downloaded.
    """
    testbed_dir = settings.paths.raw_dir / testbed
    if not (testbed_dir / "gather").is_dir():
        raise FileNotFoundError(f"{testbed_dir}: run `logtriage download --testbed {testbed}`")
    sources = load_sources(settings.paths.sources_file)
    records = build_inventory(testbed_dir, sources)

    phases = read_phase_intervals(
        settings.paths.raw_dir / "ait_ads" / settings.phases.intervals_file,
        testbed,
        settings.phases.published_source,
    )
    exfil_start, exfil_end = read_exfil_interval(testbed_dir / settings.phases.exfil_log)
    steps = read_attack_steps(testbed_dir / "gather/attacker_0/logs/attacks.log")
    steps["exfil_last_received"] = exfil_end
    checks = cross_check_phases(phases, steps, settings.phases.steps)

    # The AIT-ADS rows stay as published. The exfiltration itself is not in them (plan 5.3).
    exfil_source = f"attacker_0:{Path(settings.phases.exfil_log).name}"
    phases.append(Phase(testbed, settings.phases.exfil_phase, exfil_start, exfil_end, exfil_source))
    phases.sort(key=lambda phase: phase.start)
    write_phases_csv(phases, settings.paths.data_meta_dir / f"phases_{testbed}.csv")

    section = render_phase_section(phases, checks, settings.phases.tolerance_seconds)
    report = settings.paths.reports_dir / f"inventory_{testbed}.md"
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text(render_report(testbed, records, sources, [section]), encoding="utf-8")
    return report
